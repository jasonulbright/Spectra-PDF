#!/usr/bin/env python3
"""Generates and verifies `src/renderer/lib/bundled-faces.ts`.

The file holds the engine's face tables (`engine.font_fallback`), the
characters each bundled face holds, read from the face files, and the
characters each face holds and cannot draw alone, asked of the engine
(`engine.text_box.face_draws`). The renderer reads it to tell, without an
engine call, whether a text can be drawn.

    python scripts/gen-bundled-faces.py [--fonts DIR] [--check]
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "src" / "renderer" / "lib" / "bundled-faces.ts"


def _ranges(points) -> str:
    out: list[str] = []
    start = prev = None
    for point in sorted(points):
        if start is None:
            start = prev = point
        elif point == prev + 1:
            prev = point
        else:
            out.append(f"{start:x}" if start == prev else f"{start:x}-{prev:x}")
            start = prev = point
    if start is not None:
        out.append(f"{start:x}" if start == prev else f"{start:x}-{prev:x}")
    return ",".join(out)


def _wrapped(text: str, indent: str) -> str:
    parts = [text[i:i + 100] for i in range(0, len(text), 100)] or [""]
    return (" +\n" + indent).join(f"'{part}'" for part in parts)


def generate(fonts: Path) -> str:
    sys.path.insert(0, str(ROOT / "src"))
    from engine import font_fallback as ff
    from engine import shaping
    from engine.text_box import face_draws

    faces = {
        "serif": ff._FACE_FILES["serif"],
        "sans": ff._FACE_FILES["sans"],
        "mono": ff._FACE_FILES["mono"],
        "cjk": ff._CJK_FACES,
        "arabic": ff._RTL_FACES["arabic"],
        "hebrew": ff._RTL_FACES["hebrew"],
    }
    hints = {
        "serif": list(ff._SERIF_HINTS),
        "mono": list(ff._MONO_HINTS),
        "bold": list(ff._BOLD_HINTS),
        "italic": list(ff._ITALIC_HINTS),
    }
    files = sorted({name for table in faces.values() for name in table.values()})
    coverage: dict[str, str] = {}
    undrawn: dict[str, str] = {}
    for name in files:
        held = set(ff.face_glyph_names(str(fonts / name)))
        coverage[name] = _ranges(held)
        joins = {point for point in held if shaping.requires_shaping(chr(point))}
        # A character of no joining script is drawn by its glyph. The engine
        # is asked about every other one.
        undrawn[name] = _ranges(point for point in joins if not face_draws(str(fonts / name), chr(point)))
    sets: list[str] = []
    for name in files:
        if coverage[name] not in sets:
            sets.append(coverage[name])

    lines = [
        "// Generated by scripts/gen-bundled-faces.py from the engine's face tables",
        "// (engine/font_fallback.py), the bundled face files and the engine's shaper;",
        "// a test keeps both equal.",
        "",
        "/** The face file of each family and style. */",
        "export const BUNDLED_FACES = {",
    ]
    for family, table in faces.items():
        entries = ", ".join(f"{style}: {json.dumps(table[style])}" for style in ("regular", "bold", "italic", "bolditalic"))
        lines.append(f"  {family}: {{ {entries} }},")
    lines += ["} as const;", "", "/** The parts of a font name that select a family or a style. */", "export const FACE_HINTS = {"]
    for key, values in hints.items():
        lines.append(f"  {key}: {json.dumps(values)},")
    lines += ["} as const;", ""]
    for index, text in enumerate(sets):
        lines.append(f"const SET_{index} =\n  {_wrapped(text, '  ')};")
    lines += ["", "/** The code points each face file holds: hexadecimal ranges, comma separated. */",
              "export const FACE_COVERAGE: Readonly<Record<string, string>> = {"]
    for name in files:
        lines.append(f"  {json.dumps(name)}: SET_{sets.index(coverage[name])},")
    lines += ["};", "",
              "/** The code points a face file holds and the engine's shaper cannot draw from it. */",
              "export const FACE_UNSHAPED: Readonly<Record<string, string>> = {"]
    for name in files:
        lines.append(f"  {json.dumps(name)}: {_wrapped(undrawn[name], '    ')},")
    lines += ["};", ""]
    return "\n".join(lines).replace('"', "'")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--fonts", default=str(ROOT / "resources" / "fonts"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = generate(Path(args.fonts))
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
        if current != text:
            print(f"{TARGET.relative_to(ROOT)} is not what scripts/gen-bundled-faces.py writes", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
